void turnLeft() {
  for (int i = 0; i < sizeof(turnLeftGait) / sizeof(turnLeftGait[0]); i += NUM_JOINTS - 1) {
    for (int j = 1; j < NUM_JOINTS; j++) {
      servoSetAngle(j, zeroPositionAngles[j] + turnLeftGait[i + j - 1] * rotationDirection[j]);
    }
    delay(1);
  }
  Serial.println("turn left");
}

void turnRight() {
  for (int i = 0; i < sizeof(turnLeftGait) / sizeof(turnLeftGait[0]); i += NUM_JOINTS - 1) {
    for (int j = 1; j < NUM_JOINTS; j++) {
      if (j % 2 == 1) {
        servoSetAngle(j, zeroPositionAngles[j] + turnLeftGait[i + j] * rotationDirection[j]);
      } else {
        servoSetAngle(j, zeroPositionAngles[j] + turnLeftGait[i + j - 2] * rotationDirection[j]);
      }
    }
    delay(1);
  }
  Serial.println("turn right");
}
